# ---- enemies: abilities use the same effect verbs as Gu cards ----------------
def A(name, eff, w=1, kind="attack", **k):
    d = {"name": name, "effects": eff, "w": w, "kind": kind}
    d.update(k)
    return d

def dmg(n, **k): return dict(v="damage", n=n, **k)
def st(s, stacks, turns=3, t="enemy"): return dict(v="status", s=s, stacks=stacks, turns=turns, t=t)
def sh(n): return dict(v="shield", n=n, t="self")
def hl(n): return dict(v="heal", n=n, t="self")

